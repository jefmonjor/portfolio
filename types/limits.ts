const FULL_JOB_OFFER_CHARS = 8000
const USER_TURNS_KEPT = 9
const REPLIES_BETWEEN_THEM = USER_TURNS_KEPT - 1

export const ASSISTANT_MESSAGE_INPUT_CHARS = FULL_JOB_OFFER_CHARS
export const ASSISTANT_HISTORY_INPUT_MESSAGES =
  USER_TURNS_KEPT + REPLIES_BETWEEN_THEM
export const ASSISTANT_REPLY_MAX_CHARS = 4000
export const ASSISTANT_SIGNATURE_MAX_CHARS = 128

const LONG_JOB_POSTING_WORDS = 4000
const CHARS_PER_WORD = 6

export const CV_TAILOR_OFFER_MAX_CHARS = LONG_JOB_POSTING_WORDS * CHARS_PER_WORD
export const CV_TAILOR_OFFER_MIN_CHARS = 40

const JSON_BYTES_PER_TEXT_CHAR = 3
const JSON_TURN_KEYS_BYTES = 64
const JSON_ENVELOPE_BYTES = 1024

export const ASSISTANT_BODY_MAX_BYTES =
  ASSISTANT_HISTORY_INPUT_MESSAGES *
    (ASSISTANT_MESSAGE_INPUT_CHARS * JSON_BYTES_PER_TEXT_CHAR +
      ASSISTANT_SIGNATURE_MAX_CHARS +
      JSON_TURN_KEYS_BYTES) +
  JSON_ENVELOPE_BYTES

export const CV_TAILOR_BODY_MAX_BYTES =
  CV_TAILOR_OFFER_MAX_CHARS * JSON_BYTES_PER_TEXT_CHAR + JSON_ENVELOPE_BYTES
