// Writes lib/tech-icons.generated.ts with only the simple-icons paths the
// portfolio uses. Importing from "simple-icons" in a client component shipped
// every icon (~190 KB gzip): the package is one module the bundler cannot
// tree-shake. Run `pnpm icons` after mapping a label to a new "si*" id in
// lib/tech-icons.ts; lib/tech-icons.test.ts fails while the two disagree.
import { readFile, writeFile } from "node:fs/promises"
import { fileURLToPath } from "node:url"

import * as simpleIcons from "simple-icons"

const root = new URL("../", import.meta.url)
const source = await readFile(new URL("lib/tech-icons.ts", root), "utf8")
const names = [
  ...new Set([...source.matchAll(/"(si[A-Z]\w*)"/g)].map((match) => match[1])),
].sort()
if (names.length === 0) {
  throw new Error("lib/tech-icons.ts maps no labels to simple-icons ids")
}
const lines = names.map((name) => {
  const icon = simpleIcons[name]
  if (!icon) throw new Error(`simple-icons has no export named ${name}`)
  return `export const ${name}: TechIcon = {\n  title: ${JSON.stringify(icon.title)},\n  path: ${JSON.stringify(icon.path)},\n}`
})

const output = `// Generated by scripts/generate-tech-icons.mjs from simple-icons — do not edit.

export type TechIcon = {
  readonly title: string
  readonly path: string
}

${lines.join("\n\n")}
`

const target = new URL("lib/tech-icons.generated.ts", root)
await writeFile(target, output)
console.log(`${names.length} icons → ${fileURLToPath(target)}`)
