// The tools orbit on the home page: emits only the simple-icons it shows,
// because the package cannot be tree-shaken.
import { writeFile } from "node:fs/promises"
import { fileURLToPath } from "node:url"

import * as simpleIcons from "simple-icons"

const rings = [
  [
    "siOpenjdk",
    "siSpringboot",
    "siPostgresql",
    "siRedis",
    "siHibernate",
    "siNodedotjs",
  ],
  [
    "siReact",
    "siNextdotjs",
    "siTypescript",
    "siFlutter",
    "siTailwindcss",
    "siSupabase",
    "siDocker",
    "siKubernetes",
  ],
  [
    "siClaude",
    "siGooglegemini",
    "siGithubactions",
    "siVercel",
    "siGooglecloud",
    "siKeycloak",
    "siRedhatopenshift",
    "siJenkins",
    "siPython",
    "siGo",
  ],
]

const titles = { siOpenjdk: "Java", siRedhatopenshift: "OpenShift" }

// Brand colours this dark disappear on the dark theme; those icons take the
// text colour instead.
function isNearBlack(hex) {
  const channels = [0, 2, 4].map((at) => parseInt(hex.slice(at, at + 2), 16))
  return Math.max(...channels) < 115
}

const ringSource = rings.map((ring) => {
  const tools = ring.map((name) => {
    const icon = simpleIcons[name]
    if (!icon) throw new Error(`simple-icons has no export named ${name}`)
    const title = titles[name] ?? icon.title
    const ink = isNearBlack(icon.hex)
    return `    { title: ${JSON.stringify(title)}, hex: "#${icon.hex}", ink: ${ink}, path: ${JSON.stringify(icon.path)} },`
  })
  return `  [\n${tools.join("\n")}\n  ],`
})

const output = `// Generated by scripts/generate-site-tools.mjs from simple-icons — do not edit.

export type Tool = {
  readonly title: string
  readonly hex: string
  /** Near-black brand colour: drawn in the text colour so dark mode keeps it. */
  readonly ink: boolean
  readonly path: string
}

export const toolRings: ReadonlyArray<ReadonlyArray<Tool>> = [
${ringSource.join("\n")}
]
`

const target = new URL(
  "../components/site/tool-rings.generated.ts",
  import.meta.url
)
await writeFile(target, output)
console.log(`${rings.flat().length} tools → ${fileURLToPath(target)}`)
